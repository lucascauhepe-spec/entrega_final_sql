-- Vista de productos con tratamiento de precios NULL
CREATE OR REPLACE VIEW productos_limpios AS
SELECT
    producto_id,
    nombre,
    categoria,
    COALESCE(precio, 0) AS precio,
    stock,
    descripcion,
    atributos
FROM productos;


-- Vista de pedidos con tratamiento de precios unitarios NULL
